local GuideProfiles = Advisor.GuideProfiles
local byClass = {}

local function Normalize(value)
    value = string.lower(tostring(value or ""))
    value = string.gsub(value, "[^%w]", "")
    return value
end

local function IndexAlias(classKey, alias)
    local normalized = Normalize(alias)
    if normalized ~= "" then byClass[normalized] = classKey end
end

GuideProfiles.classes = {}
for _, profile in ipairs(GuideProfiles.profiles) do
    local class = GuideProfiles.classes[profile.classKey]
    if not class then
        class = { profiles = {}, bySpecialization = {} }
        GuideProfiles.classes[profile.classKey] = class
    end
    class.profiles[#class.profiles + 1] = profile
    class.bySpecialization[Normalize(profile.specializationName)] = profile
    IndexAlias(profile.classKey, profile.classKey)
    IndexAlias(profile.classKey, profile.className)
    for _, alias in ipairs(profile.classAliases or {}) do
        IndexAlias(profile.classKey, alias)
    end
end

function GuideProfiles.ResolveClassKey(classToken, className)
    return byClass[Normalize(classToken)] or byClass[Normalize(className)]
end

function GuideProfiles.Find(classToken, className, specializationName)
    local classKey = GuideProfiles.ResolveClassKey(classToken, className)
    local class = classKey and GuideProfiles.classes[classKey]
    if not class then return nil end
    return class.bySpecialization[Normalize(specializationName)]
end

function GuideProfiles.FindByNames(className, specializationName)
    return GuideProfiles.Find(nil, className, specializationName)
end

function GuideProfiles.AddSpecializationAlias(profile, alias)
    if not profile or not alias then return false end
    local class = GuideProfiles.classes[profile.classKey]
    local normalized = Normalize(alias)
    if not class or normalized == "" then return false end
    class.bySpecialization[normalized] = profile
    return true
end

function GuideProfiles.GetAll()
    return GuideProfiles.profiles
end

function GuideProfiles.Normalize(value)
    return Normalize(value)
end
